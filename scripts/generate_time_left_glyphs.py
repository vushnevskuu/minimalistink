#!/usr/bin/env python3
"""Generate src/images/TimeLeftGlyphs.h, the large 1-bit glyphs of the Time Left sleep screen.

Usage: uv run --no-project --with pillow python scripts/generate_time_left_glyphs.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "lib/EpdFont/builtinFonts/source/Ubuntu"
OUT = ROOT / "src/images/TimeLeftGlyphs.h"
NUMBER_SIZE = 300
UNIT_SIZE = 104


def glyph(font, char, name):
    x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
    width, height = x1 - x0, y1 - y0
    image = Image.new("1", (width, height), 0)
    draw = ImageDraw.Draw(image)
    draw.fontmode = "1"
    draw.text((-x0, -y0), char, font=font, fill=1, anchor="ls")
    rows = bytearray()
    for y in range(height):
        for start in range(0, width, 8):
            byte = 0
            for x in range(start, start + 8):
                byte = (byte << 1) | (1 if x < width and image.getpixel((x, y)) else 0)
            rows.append(byte)
    lines = [", ".join(f"0x{b:02X}" for b in rows[i : i + 20]) for i in range(0, len(rows), 20)]
    body = ",\n    ".join(lines)
    data = f"static const uint8_t {name}Bits[] = {{\n    {body}}};\n"
    entry = f"{{{width}, {height}, {-y0}, {x0}, {round(font.getlength(char))}, {name}Bits}}"
    return data, entry, len(rows)


number = ImageFont.truetype(str(FONT_DIR / "Ubuntu-Bold.ttf"), NUMBER_SIZE)
unit = ImageFont.truetype(str(FONT_DIR / "Ubuntu-Regular.ttf"), UNIT_SIZE)
parts, digits, total = [], [], 0
for char in "0123456789":
    data, entry, size = glyph(number, char, f"kDigit{char}")
    parts.append(data)
    digits.append(entry)
    total += size
extras = []
for font, char, name in ((number, "<", "kLess"), (unit, "h", "kUnitH"), (unit, "ч", "kUnitCh")):
    data, entry, size = glyph(font, char, name)
    parts.append(data)
    extras.append((name, entry))
    total += size

text = """// Generated by scripts/generate_time_left_glyphs.py. Do not edit.
#pragma once
#include <cstdint>

// clang-format off
// 1-bit, MSB first, rows padded to whole bytes.
struct TimeLeftGlyph {
  uint16_t width;
  uint16_t height;
  int16_t top;  // pixels above the baseline
  int16_t left;
  uint16_t advance;
  const uint8_t* bits;
};

"""
text += "\n".join(parts)
text += "\nstatic const TimeLeftGlyph TIME_LEFT_DIGITS[10] = {\n    " + ",\n    ".join(digits) + "};\n"
for name, entry in extras:
    text += f"static const TimeLeftGlyph {name}Glyph = {entry};\n"
OUT.write_text(text, encoding="utf-8")
print(f"{OUT.name}: {total} bytes of glyph data")
